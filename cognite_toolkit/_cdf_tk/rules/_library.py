def get_rules_library() -> list[RuleDefinition]:
    """All rules reported by the Toolkit, in the order they are listed in the rules library documentation."""
    contexts: tuple[RuleContext, ...] = get_args(RuleContext)
    severities: tuple[RuleSeverity, ...] = get_args(RuleSeverity)
    rules = [rule for rule_set in get_global_rules_registry() for rule in rule_set.RULES]
    rules.extend(_UNMIGRATED_RULES)
    return sorted(
        rules,
        key=lambda rule: (
            rule.code,
            contexts.index(rule.context),
            severities.index(rule.severity),
            rule.resource_types,
        ),
    )
