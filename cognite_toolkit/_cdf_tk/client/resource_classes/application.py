"""Application request and response classes.

Based on the alpha API specification at:
https://api-docs.cognite.com/20230101-alpha/tag/Applications
"""

from typing import Any, ClassVar, Literal

from pydantic import Field

from cognite_toolkit._cdf_tk.client._resource_base import (
    BaseModelObject,
    ResponseResource,
    UpdatableRequestResource,
)
from cognite_toolkit._cdf_tk.client.identifiers import ApplicationId


class Application(BaseModelObject):
    """Base class for applications registered for an organization."""

    name: str
    description: str | None = None
    project_names: list[str]


class ApplicationRequest(Application, UpdatableRequestResource):
    """Application request resource for creating and updating applications."""

    non_nullable_fields: ClassVar[frozenset[str]] = frozenset({"name", "allowed_origins", "project_names"})
    # The client ID is generated by the API on create and is only used to identify the application on update.
    id: str | None = Field(default=None, exclude=True)
    allowed_origins: list[str] | None = None

    def as_id(self) -> ApplicationId:
        if self.id is None:
            raise ValueError("Cannot convert ApplicationRequest to ApplicationId when id is None")
        return ApplicationId(id=self.id)

    def as_update(self, mode: Literal["patch", "replace"]) -> dict[str, Any]:
        # The API only supports replacing the list of allowed origins, so replace clears it when unset.
        update_item = super().as_update(mode)
        if mode == "replace" and self.allowed_origins is None:
            update_item["update"]["allowedOrigins"] = {"set": []}
        return update_item


class ApplicationResponse(Application, ResponseResource[ApplicationRequest]):
    """Application response resource returned from the API."""

    id: str
    allowed_origins: list[str]
    created_time: int
    last_updated_time: int

    def as_id(self) -> ApplicationId:
        return ApplicationId(id=self.id)

    @classmethod
    def request_cls(cls) -> type[ApplicationRequest]:
        return ApplicationRequest
